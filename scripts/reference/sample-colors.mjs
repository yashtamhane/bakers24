// Samples colours from the approved reference and records them for the style guide.
//   npm run ref:colors
// Writes:
//   src/styleguide/reference-colors.json   (committed; read by /_styleguide)
//   .reference-output/color-samples.png    (reference annotated with sample boxes)
//   src/styleguide/reference-crops/color-samples.jpg  (smaller copy for /_styleguide)

import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { COLOR_SAMPLES, OUTPUT_DIR, REFERENCE_IMAGE, ROOT } from "./regions.mjs";

const INK_FRACTION = 0.12;

const toHex = (rgb) => "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase();
const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;

async function readPixels(rect) {
  const [left, top, width, height] = rect;
  const { data } = await sharp(REFERENCE_IMAGE)
    .removeAlpha()
    .extract({ left, top, width, height })
    .raw()
    .toBuffer({ resolveWithObject: true });
  const pixels = [];
  for (let i = 0; i < data.length; i += 3) pixels.push([data[i], data[i + 1], data[i + 2]]);
  return pixels;
}

function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
}

function summarise(pixels, mode) {
  if (mode === "fill") {
    return [0, 1, 2].map((c) => median(pixels.map((p) => p[c])));
  }
  const byLuma = [...pixels].sort((a, b) => luma(...a) - luma(...b));
  const count = Math.max(1, Math.round(byLuma.length * INK_FRACTION));
  const ink = mode === "ink-light" ? byLuma.slice(-count) : byLuma.slice(0, count);
  return [0, 1, 2].map((c) => ink.reduce((sum, p) => sum + p[c], 0) / ink.length);
}

const results = [];
for (const sample of COLOR_SAMPLES) {
  const rgb = summarise(await readPixels(sample.rect), sample.mode);
  results.push({ ...sample, hex: toHex(rgb) });
}

const outFile = path.join(ROOT, "src/styleguide/reference-colors.json");
await fs.mkdir(path.join(ROOT, "src/styleguide/reference-crops"), { recursive: true });
await fs.writeFile(
  outFile,
  JSON.stringify(
    {
      source: "references/approved-design.png",
      method: `fill = per-channel median; ink = mean of the ${INK_FRACTION * 100}% brightest/darkest pixels`,
      note: "Generated by scripts/reference/sample-colors.mjs. Samples come from a compressed AI-rendered collage, so treat them as targets, not exact brand values.",
      samples: results.map(({ id, panel, role, mode, rect, hex }) => ({ id, panel, role, mode, rect, hex })),
    },
    null,
    2,
  ) + "\n",
);

// Annotated reference so sample placement can be checked by eye.
await fs.mkdir(OUTPUT_DIR, { recursive: true });
const boxes = COLOR_SAMPLES.map(
  ({ rect: [x, y, w, h] }) =>
    `<rect x="${x - 1}" y="${y - 1}" width="${w + 2}" height="${h + 2}" fill="none" stroke="#00FF88" stroke-width="1.5"/>`,
).join("");
const { width, height } = await sharp(REFERENCE_IMAGE).metadata();
await sharp(REFERENCE_IMAGE)
  .composite([{ input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">${boxes}</svg>`) }])
  .png()
  .toFile(path.join(OUTPUT_DIR, "color-samples.png"));
// Smaller copy for /_styleguide (internal comparison aid only).
await sharp(path.join(OUTPUT_DIR, "color-samples.png"))
  .resize({ width: 1200 })
  .jpeg({ quality: 78, mozjpeg: true })
  .toFile(path.join(ROOT, "src/styleguide/reference-crops/color-samples.jpg"));

for (const r of results) console.log(`${r.id.padEnd(22)} ${r.hex}  ${r.role}`);
console.log(`\nWrote ${path.relative(ROOT, outFile)} and .reference-output/color-samples.png`);
